void vConfigureTimerForRunTimeStats(void) {
    RCC->APB1ENR |= RCC_APB1ENR_TIM4EN;
    __DSB();
    TIM4->PSC = 4000; // Предделитель для 1 мкс
    TIM4->ARR = 0xffff; // Максимальное значение
    TIM4->CR1 |= TIM_CR1_CEN; // Включаем таймер
}

