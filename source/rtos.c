/**
 * @brief   Задача мигания светодиодом
 * @param   pvParameters  Не используется
 */
static void vLED_Task(void *pvParameters) {
    (void)pvParameters;  // Подавляем предупреждение о неиспользуемом параметре

    for (;;) {
        #ifdef DEBUG
        Task_VD_Start();
        #endif
        BIT_BAND(GPIOC_BASE,0x0C,13) = 0;
        #ifdef DEBUG
        Task_VD_Stop();
        #endif
        vTaskDelay(pdMS_TO_TICKS(1000));
        #ifdef DEBUG
        Task_VD_Start();
        #endif
        BIT_BAND(GPIOC_BASE,0x0C,13) = 1;
        #ifdef DEBUG
        uxStackHighWaterMark = uxTaskGetStackHighWaterMark(NULL);
        Task_VD_Stop();
        #endif
        vTaskDelay(pdMS_TO_TICKS(1000));
    }
}

static void vUSART_Task(void *pvParameters) {
    (void) pvParameters;
    for(;;) {
        ulTaskNotifyTake(pdTRUE,portMAX_DELAY);
        #ifdef DEBUG
        Task_USART_Start();
        #endif
        if (DMA1->ISR & DMA_ISR_TCIF4) {
            DMA1_Channel4->CCR &= ~DMA_CCR4_EN;
            DMA1_Channel4->CNDTR = BUF_ADC_SIZE;
            DMA1_Channel4->CCR |= DMA_CCR4_EN;
        }
        //USART_TX("z", USART_UNIT_1);
        #ifdef DEBUG
        Task_USART_Stop();
        #endif
    }
}

static void vFFT_Task(void *pvParameters) {
    (void) pvParameters;
    uint32_t freq;
    for(;;) {
        ulTaskNotifyTake(pdTRUE,portMAX_DELAY);
        #ifdef DEBUG
        Task_FFT_Start();
        #endif
        for(int i = 0; i<BUF_ADC_SIZE; i++) {
            sec_buf_adc[i] = (sec_buf_adc[i] - 2048) << 4;
        }
        arm_rfft_q15(&S, (q15_t *)sec_buf_adc, buf_fft);
        arm_cmplx_mag_squared_q15(buf_fft,magn_half_buf_fft, BUF_ADC_SIZE/2);
        arm_max_q15(magn_half_buf_fft, BUF_ADC_SIZE/2, &dummy, &ind_max_magn);
        freq = ind_max_magn * bin_freq;
        xTaskNotifyGive(usart_task);
        xTaskNotify(oled_task, freq, eSetValueWithoutOverwrite);
        #ifdef DEBUG
        Task_FFT_Stop();
        uxStackHighWaterMark = uxTaskGetStackHighWaterMark(NULL);
        #endif
    }
}

static void OLED_Display(void *pvParameters) {
    (void) pvParameters;
    uint32_t freq_from_fft_task;
    uint8_t digits[4];
    uint8_t NEW_FRAME_BITMAP[1024];
    uint8_t * p_to_NFB;
    memset(NEW_FRAME_BITMAP,0,sizeof(NEW_FRAME_BITMAP));

    for(;;) {
        xTaskNotifyWait(0,0xFFFFFFFF,&freq_from_fft_task,portMAX_DELAY);
        #ifdef DEBUG
        Task_OLED_Start();
        #endif
        for (int i = 3; i >= 0; i--) {
            digits[i] = freq_from_fft_task % 10;
            freq_from_fft_task /= 10;
        }
        p_to_NFB = NEW_FRAME_BITMAP + 26*8;
        for(int i = 0; i<=3; i++) {
            memcpy(p_to_NFB,FRAME_BITMAP+digits[i]*12*8,12*8);
            p_to_NFB += 12*8 + 8*8;
        }
        SSD1306_UpdateFull(NEW_FRAME_BITMAP);
        #ifdef DEBUG
        Task_OLED_Stop();
        #endif
        vTaskDelay(pdMS_TO_TICKS(1000));
    }
}

